#!/usr/bin/env python3
"""Write ccsb-redirects.conf (Apache mod_rewrite rules) from redirects.tsv.

    python3 make_conf.py            # reads redirects.tsv, writes ccsb-redirects.conf

redirects.tsv has one row per old ccsb.scripps.edu path: old_path, new_url, kind.
A path ending in "/*" is a catch-all for everything under that folder; catch-alls are written
last, because mod_rewrite stops at the first matching rule ([L]).
"""
import csv, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
rows = list(csv.DictReader(open(HERE / "redirects.tsv"), delimiter="\t"))
specific = [r for r in rows if not r["old_path"].endswith("/*")]
catchall = [r for r in rows if r["old_path"].endswith("/*")]
sites = [r["old_path"][1:-2] for r in catchall]

def pattern(path):
    """Regex for one old path; the leading '/?' makes it work in a <VirtualHost> and in .htaccess."""
    p = re.escape(path.strip("/"))
    if path.endswith("/"):
        p += "/?"          # with or without the trailing slash
    return f"^/?{p}$"

out = [
    "# Redirects from the retired ccsb.scripps.edu subsites to sannerlab.github.io",
    "# Generated by make_conf.py from redirects.tsv; edit the TSV, not this file.",
    "#",
    "# Put these lines in the ccsb.scripps.edu <VirtualHost> (they then run before WordPress's own",
    "# rewrite rules), or at the very top of the site's .htaccess, before the WordPress block.",
    "# Flags: R=301 permanent redirect, L stop at the first match, NE keep '#anchor' in the target,",
    "# QSD drop any query string.",
    "",
    "RewriteEngine On",
    "",
    "# Leave WordPress admin and login working (until the subsites are deleted).",
    f"RewriteRule ^/?({'|'.join(sites)})/(wp-admin|wp-login\\.php|wp-json)(/.*)?$ - [L]",
    "",
]
for kind in ["page", "download", "file", "pip-index", "pip-file"]:
    sel = [r for r in specific if r["kind"] == kind]
    if not sel:
        continue
    out.append(f"# {kind} ({len(sel)})")
    out += [f'RewriteRule "{pattern(r["old_path"])}" "{r["new_url"]}" [R=301,L,NE,QSD]' for r in sel]
    out.append("")
out.append(f"# catch-all: anything else under a subsite goes to the tool's overview ({len(catchall)})")
for r in catchall:
    site = re.escape(r["old_path"][1:-2])
    out.append(f'RewriteRule "^/?{site}(/.*)?$" "{r["new_url"]}" [R=301,L,NE,QSD]')
out.append("")
(HERE / "ccsb-redirects.conf").write_text("\n".join(out))
print(f"wrote {len(specific) + len(catchall)} rules to ccsb-redirects.conf")
