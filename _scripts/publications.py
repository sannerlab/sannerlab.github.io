"""Pre-render step: build publications.qmd from _data/citations.yaml.

citations.yaml is the Manubot output carried over from the Jekyll site
(DOIs listed in _data/sources.yaml). Edit sources, not the generated page.
"""
import re
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def clean_title(t):
    t = " ".join(t.split())
    # small caps written as "A <scp>uto</scp> D <scp>ock</scp>" -> "AutoDock"
    t = re.sub(r"\b([A-Z]) ?<scp>(\w+)</scp> ?", r"\1\2", t)
    t = re.sub(r"\s*<scp>(.*?)</scp>\s*", r" \1 ", t)
    t = re.sub(r"\s+:", ":", t)
    return " ".join(t.split())


def main():
    cites = yaml.safe_load((ROOT / "_data" / "citations.yaml").read_text())
    by_year = defaultdict(list)
    for c in cites:
        by_year[str(c.get("date", ""))[:4] or "Undated"].append(c)

    out = [
        "---",
        "title: Publications",
        'title-block-banner: "#6a3fa0"',
        'title-block-banner-color: "#ffffff"',
        "toc: false",
        "---",
        "",
        "<!-- GENERATED by _scripts/publications.py from _data/citations.yaml. Do not edit. -->",
        "",
        f"{len(cites)} journal and preprint papers by Michel Sanner and colleagues, newest first.",
        "",
    ]
    for year in sorted(by_year, reverse=True):
        out += [f"## {year}", "", '<ul class="pub-list">']
        for c in sorted(by_year[year], key=lambda c: str(c.get("date", "")), reverse=True):
            authors = ", ".join(c.get("authors", []))
            authors = authors.replace("Michel F. Sanner", "<strong>Michel F. Sanner</strong>")
            title = clean_title(c["title"])
            link = c.get("link", "")
            venue = c.get("publisher", "")
            out.append(
                f'<li><a href="{link}">{title}</a><br>{authors}. '
                f'<span class="pub-venue">{venue}</span> ({year}).</li>'
            )
        out += ["</ul>", ""]
    (ROOT / "publications.qmd").write_text("\n".join(out))


if __name__ == "__main__":
    main()
